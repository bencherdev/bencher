/** A path a classic route answered, each `[param]` filled from `params`. */
export const classicPath = (
	route: string,
	params: Readonly<Record<string, string>>,
): string =>
	`/${route}`
		.replace(/(\/index)?\.astro$/, "")
		.replace(/\[(\w+)\]/g, (_, name: string) => params[name] ?? name);
